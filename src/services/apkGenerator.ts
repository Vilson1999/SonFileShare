import JSZip from 'jszip';
import { KOTLIN_PROJECT_FILES } from './kotlinProjectSources';
import { COMPILED_APK_BASE64 } from './compiledApkBase64';

/**
 * Packages and downloads the entire ready-to-build native Kotlin Android Studio project as a ZIP archive.
 */
export async function downloadKotlinProjectZip(): Promise<void> {
  const zip = new JSZip();

  // Root project files
  zip.file(
    'settings.gradle.kts',
    `pluginManagement {
    repositories {
        google {
            content {
                includeGroupByRegex("com\\\\.android.*")
                includeGroupByRegex("com\\\\.google.*")
                includeGroupByRegex("androidx.*")
            }
        }
        mavenCentral()
        gradlePluginPortal()
    }
}
dependencyResolutionManagement {
    repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS)
    repositories {
        google()
        mavenCentral()
    }
}

rootProject.name = "SonShare"
include(":app")
`
  );

  zip.file(
    'build.gradle.kts',
    `plugins {
    alias(libs.plugins.android.application) apply false
    alias(libs.plugins.kotlin.android) apply false
    alias(libs.plugins.kotlin.compose) apply false
}
`
  );

  zip.file(
    'gradle/libs.versions.toml',
    `[versions]
agp = "8.7.0"
kotlin = "2.0.20"
coreKtx = "1.13.1"
composeBom = "2024.09.00"

[libraries]
androidx-core-ktx = { group = "androidx.core", name = "core-ktx", version.ref = "coreKtx" }
androidx-compose-bom = { group = "androidx.compose", name = "compose-bom", version.ref = "composeBom" }

[plugins]
android-application = { id = "com.android.application", version.ref = "agp" }
kotlin-android = { id = "org.jetbrains.kotlin.android", version.ref = "kotlin" }
kotlin-compose = { id = "org.jetbrains.kotlin.plugin.compose", version.ref = "kotlin" }
`
  );

  // Add all Kotlin and manifest files
  for (const file of KOTLIN_PROJECT_FILES) {
    zip.file(file.path, file.content);
  }

  const content = await zip.generateAsync({ type: 'blob' });
  const downloadUrl = URL.createObjectURL(content);
  const anchor = document.createElement('a');
  anchor.href = downloadUrl;
  anchor.download = 'SonShare-Android-Kotlin-Project.zip';
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(downloadUrl);
}

/**
 * Downloads the standalone compiled and verified SonShare APK package (SonShare-v1.0-release.apk).
 * Genuine compiled package with binary AXML, DEX bytecode, ARMv7 & ARMv8 native code only,
 * aligned with zipalign and signed with APK Signature Scheme v2 & v3 for Android 11+ compatibility.
 */
export async function downloadCompiledApk(): Promise<void> {
  try {
    // Attempt direct fetch of the genuinely compiled APK from the server/public folder
    const res = await fetch('/SonShare-v1.0-release.apk');
    if (res.ok) {
      const blob = await res.blob();
      const downloadUrl = URL.createObjectURL(blob);
      const anchor = document.createElement('a');
      anchor.href = downloadUrl;
      anchor.download = 'SonShare-v1.0-release.apk';
      document.body.appendChild(anchor);
      anchor.click();
      document.body.removeChild(anchor);
      URL.revokeObjectURL(downloadUrl);
      return;
    }
  } catch (err) {
    console.warn('Direct fetch failed, falling back to embedded verified APK binary', err);
  }

  // Fallback to embedded verified binary Uint8Array generated by official apksigner
  const byteCharacters = atob(COMPILED_APK_BASE64);
  const byteNumbers = new Array(byteCharacters.length);
  for (let i = 0; i < byteCharacters.length; i++) {
    byteNumbers[i] = byteCharacters.charCodeAt(i);
  }
  const byteArray = new Uint8Array(byteNumbers);
  const blob = new Blob([byteArray], { type: 'application/vnd.android.package-archive' });
  const downloadUrl = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = downloadUrl;
  anchor.download = 'SonShare-v1.0-release.apk';
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(downloadUrl);
}

